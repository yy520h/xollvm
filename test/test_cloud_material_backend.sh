#!/bin/bash
# 测试 CloudMaterial 后端打包功能

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

echo "=== CloudMaterial 后端打包测试 ==="
echo ""

# 创建测试输出目录
TEST_OUTPUT="$PROJECT_ROOT/test_output/cloud_material_backend"
rm -rf "$TEST_OUTPUT"
mkdir -p "$TEST_OUTPUT/windows"

echo "测试输出目录: $TEST_OUTPUT"
echo ""

# 1. 生成模拟窗口文件
echo "[1/5] 生成模拟窗口文件..."
for i in {0..4}; do
    for s in {0..1}; do
        dd if=/dev/urandom of="$TEST_OUTPUT/windows/test_material_w${i}_s${s}.bin" bs=2048 count=1 2>/dev/null
    done
done
echo "✓ 生成了 10 个窗口文件"
echo ""

# 2. 创建材料信息 JSON
echo "[2/5] 创建材料信息..."
cat > "$TEST_OUTPUT/material_info.json" << 'EOF'
{
  "materials": [
    {
      "id": "test_material",
      "total_size": 10240,
      "window_count": 5,
      "shard_count": 2,
      "commitment": "sha256:1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef",
      "window_dir": "windows"
    }
  ]
}
EOF
echo "✓ 材料信息已创建"
echo ""

# 3. 测试 Direct 模式配置生成
echo "[3/5] 测试 Direct 模式配置..."

SECRET=$(openssl rand -hex 32)
cat > "$TEST_OUTPUT/backend_config_direct.json" << EOF
{
  "output_dir": "$TEST_OUTPUT",
  "app_id": "com.example.testapp",
  "app_version": "1.0.0",
  "mode": "direct",
  "hmac_secret": "$SECRET",
  "enable_tls": true,
  "ndk_path": "$PROJECT_ROOT"
}
EOF

echo "✓ Direct 模式配置已生成"
echo "  HMAC Secret: $SECRET"
echo ""

# 4. 测试 Zone 模式配置生成
echo "[4/5] 测试 Zone 模式配置..."

ZONE_TOKEN=$(openssl rand -hex 32)
cat > "$TEST_OUTPUT/backend_config_zone.json" << EOF
{
  "output_dir": "$TEST_OUTPUT",
  "app_id": "com.example.testapp",
  "app_version": "1.0.0",
  "mode": "zone",
  "zone_token": "$ZONE_TOKEN",
  "enable_tls": false,
  "ndk_path": "$PROJECT_ROOT"
}
EOF

echo "✓ Zone 模式配置已生成"
echo "  Zone Token: $ZONE_TOKEN"
echo ""

# 5. 模拟 VMPass 调用（手动创建预期的输出）
echo "[5/5] 模拟后端包生成..."

# 创建 backend_package 目录结构
PACKAGE_DIR="$TEST_OUTPUT/backend_package"
mkdir -p "$PACKAGE_DIR/windows"

# 生成 metadata.json
cat > "$PACKAGE_DIR/metadata.json" << EOF
{
  "app_id": "com.example.testapp",
  "version": "1.0.0",
  "build_time": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "window_size": 2048,
  "chaff_ratio": 0.3,
  "materials": {
    "test_material": {
      "id": "test_material",
      "total_size": 10240,
      "window_count": 5,
      "shard_count": 2,
      "commitment": "sha256:1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef"
    }
  }
}
EOF

# 生成 config.yaml (Direct 模式)
cat > "$PACKAGE_DIR/config.yaml" << EOF
app:
  id: "com.example.testapp"
  version: "1.0.0"

mode: direct

direct:
  listen: "0.0.0.0:8080"
  auth_method: hmac
  secret: "$SECRET"
  tls:
    enabled: true
    cert: "/path/to/cert.pem"
    key: "/path/to/key.pem"
  security:
    rate_limit:
      enabled: true
      requests_per_device_per_minute: 100
      requests_per_ip_per_minute: 500
    replay_protection:
      enabled: true
      time_window_seconds: 300
      nonce_cache_size: 10000

storage:
  windows_dir: "./windows/"
  metadata_file: "./metadata.json"

logging:
  level: "info"
EOF

# 复制窗口文件
cp -r "$TEST_OUTPUT/windows/"*.bin "$PACKAGE_DIR/windows/"

# 生成 DEPLOY.txt
cat > "$PACKAGE_DIR/DEPLOY.txt" << EOF
=== xollvm Backend 部署包 ===

应用: com.example.testapp v1.0.0
模式: direct
生成时间: $(date -u +%Y-%m-%dT%H:%M:%SZ)

部署步骤:

1. 上传此目录所有文件到服务器:
   scp -r backend_package/* user@your-server:/opt/xollvm-backend/

2. (推荐) 生成 TLS 证书:
   cd /opt/xollvm-backend
   openssl req -x509 -newkey rsa:4096 -keyout key.pem -out cert.pem -days 365 -nodes
   然后更新 config.yaml 中的证书路径

3. 在客户端配置中设置:
   - 后端 URL: https://your-server:8080
   - HMAC Secret: $SECRET

4. 启动服务器:
   chmod +x xollvm-backend-server
   ./xollvm-backend-server -config config.yaml

5. 检查服务状态:
   curl http://localhost:8080/health

详细文档请参考 README.md
EOF

# 复制 README
if [ -f "$PROJECT_ROOT/xollvm-backend-server/README.md" ]; then
    cp "$PROJECT_ROOT/xollvm-backend-server/README.md" "$PACKAGE_DIR/"
fi

# 生成客户端配置头文件
cat > "$TEST_OUTPUT/xollvm_cloud_config.h" << EOF
// Auto-generated by xollvm CloudMaterial
// DO NOT EDIT MANUALLY

#ifndef XOLLVM_CLOUD_CONFIG_H
#define XOLLVM_CLOUD_CONFIG_H

namespace xovm {
namespace material {

// 后端配置
constexpr const char* BACKEND_MODE = "direct";
constexpr const char* BACKEND_URL = "https://your-server:8080";
constexpr const char* HMAC_SECRET = "$SECRET";
constexpr bool ENABLE_TLS = true;

} // namespace material
} // namespace xovm

#endif // XOLLVM_CLOUD_CONFIG_H
EOF

# 创建占位符后端二进制
touch "$PACKAGE_DIR/xollvm-backend-server"
chmod +x "$PACKAGE_DIR/xollvm-backend-server"

echo "✓ 后端包已生成"
echo ""

# 打包
echo "打包中..."
cd "$TEST_OUTPUT"
tar czf backend_package.tar.gz backend_package
echo "✓ 已创建: backend_package.tar.gz"
echo ""

# 验证生成的文件
echo "=== 验证生成的文件 ==="
echo ""

echo "1. 目录结构:"
tree -L 2 "$PACKAGE_DIR" 2>/dev/null || find "$PACKAGE_DIR" -type f | head -20

echo ""
echo "2. metadata.json 内容:"
cat "$PACKAGE_DIR/metadata.json" | head -20

echo ""
echo "3. config.yaml 内容 (前 15 行):"
head -15 "$PACKAGE_DIR/config.yaml"

echo ""
echo "4. 窗口文件:"
ls -lh "$PACKAGE_DIR/windows/" | head -10

echo ""
echo "5. 客户端配置头文件:"
cat "$TEST_OUTPUT/xollvm_cloud_config.h"

echo ""
echo "6. 部署包大小:"
ls -lh "$TEST_OUTPUT/backend_package.tar.gz"

echo ""
echo "=== 测试完成 ==="
echo ""
echo "测试结果:"
echo "  ✓ 窗口文件生成"
echo "  ✓ metadata.json 生成"
echo "  ✓ config.yaml 生成"
echo "  ✓ DEPLOY.txt 生成"
echo "  ✓ 客户端配置头文件生成"
echo "  ✓ 部署包打包"
echo ""
echo "输出位置: $TEST_OUTPUT"
echo "部署包: $TEST_OUTPUT/backend_package.tar.gz"
echo ""
echo "后续步骤:"
echo "1. 将 backend_package.tar.gz 部署到服务器"
echo "2. 在客户端代码中 #include \"xollvm_cloud_config.h\""
echo "3. 使用生成的 HMAC_SECRET 进行认证"
